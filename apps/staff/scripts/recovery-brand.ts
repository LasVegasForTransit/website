import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

const root = new URL('../', import.meta.url);
const output = new URL('../../packages/platform-core/src/staff-gate-brand.ts', root);
function rule(source: string, selector: string): string {
  const start = source.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`Missing shared brand rule: ${selector}`);
  const open = source.indexOf('{', start);
  let depth = 1;
  let end = open + 1;
  while (depth > 0 && end < source.length) {
    if (source[end] === '{') depth++;
    if (source[end] === '}') depth--;
    end++;
  }
  if (depth !== 0) throw new Error(`Unclosed shared brand rule: ${selector}`);
  return source.slice(start, end);
}
export async function recoveryBrandSource(): Promise<string> {
  const [globalSource, staffSource, font, lightLogo, darkLogo] = await Promise.all([
    readFile(new URL('../../site/src/styles/global.css', import.meta.url), 'utf8'),
    readFile(new URL('src/styles/staff.css', root), 'utf8'),
    readFile(new URL('../../site/public/fonts/public-sans-latin.woff2', import.meta.url), 'base64'),
    readFile(new URL('../../site/public/brand/lvbt-logo.svg', import.meta.url), 'utf8'),
    readFile(new URL('../../site/public/brand/lvbt-logo-dark.svg', import.meta.url), 'utf8'),
  ]);
  const globalCss = globalSource.replace(/\/\*[\s\S]*?\*\//g, '');
  const staffCss = staffSource.replace(/\/\*[\s\S]*?\*\//g, '');
  const styles = [
    rule(globalCss, '@font-face').replace(
      "url('/fonts/public-sans-latin.woff2')",
      `url('data:font/woff2;base64,${font}')`,
    ),
    rule(globalCss, ':root'),
    rule(globalCss, '@theme').replace('@theme', ':root'),
    rule(globalCss, '@media (prefers-color-scheme: dark)'),
    rule(globalCss, 'html'),
    rule(globalCss, '.container-page'),
    ...[
      '.staff-header',
      '.staff-header-inner',
      '.staff-identity',
      '.staff-identity-mark',
      '.staff-identity span',
      '.staff-main',
      '.staff-page-heading',
      '.staff-heading-copy',
      '.staff-page-heading h1',
      '.staff-heading-copy > p',
      '.staff-shell .staff-action-link',
      '.staff-shell .staff-action-link:focus-visible',
      '.staff-shell .staff-secondary-button',
      '.staff-shell .staff-secondary-button:focus-visible',
      '.staff-muted-link',
    ].map((selector) => rule(staffCss, selector)),
  ].join('\n');
  return await format(
    `// Generated by pnpm -C apps/staff brand:recovery from the normal staff brand sources.\nexport const recoveryBrandStyles =\n  ${JSON.stringify(styles)};\nexport const recoveryLightLogo =\n  ${JSON.stringify(lightLogo)};\nexport const recoveryDarkLogo =\n  ${JSON.stringify(darkLogo)};\n`,
    { parser: 'typescript', singleQuote: true, printWidth: 100 },
  );
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const expected = await recoveryBrandSource();
  if (process.argv.includes('--check')) {
    if ((await readFile(output, 'utf8')) !== expected)
      throw new Error('Recovery brand is stale. Run pnpm -C apps/staff brand:recovery.');
  } else {
    await writeFile(output, expected);
  }
}
